@dataclass(frozen=True)
class OrbitalElements:
    """Оскулирующие элементы орбиты планеты на эпоху D0."""
    name: str                 # название планеты
    a: float                  # большая полуось, км
    e: float                  # эксцентриситет
    i: float                  # наклонение, рад
    omega_node: float         # долгота восходящего узла Омега, рад
    pi_lon: float             # средняя долгота перицентра пи, рад
    n: float                  # среднесуточное движение, рад/сут
    lam: float                # средняя долгота на эпоху D0, рад
    mu: float                 # гравитационный параметр планеты, км^3/с^2
    r_sphere: float           # радиус сферы действия планеты, км
    radius: float             # средний радиус планеты, км


