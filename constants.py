# варианты
@dataclass(frozen=True)
class Variant:
    """Вариант задания: дата старта, время перелёта, высоты орбит ИС."""
    number: int               # номер варианта
    planet: str               # планета назначения
    date_start: str           # дата старта D1 в формате ДД.ММ.ГГГГ
    t12_days: float           # продолжительность перелёта t12, сут
    h_isz_km: float           # высота круговой орбиты ИСЗ, км
    h_isp_km: float           # высота круговой орбиты ИС планеты назначения, км


def _v(number: int, date_start: str, t12: float, h_isz: float, h_isp: float) -> Variant:
    """Вспомогательная функция создания варианта (планета всегда Марс)."""
    return Variant(number, "Марс", date_start, t12, h_isz, h_isp)


